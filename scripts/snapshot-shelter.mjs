#!/usr/bin/env node
// scripts/snapshot-shelter.mjs  (owner: R, TOKENTAILS-PLAN §12.1): writes src/shelter/snapshot.js, the bundled list of
// Pink Paw cats the game uses on any host that may not call the API (localhost, previews, other sites).
// Source: GET https://api.tokentails.com/shelter/rozine-pedute/gallery (public, read only), or a saved body:
//   node scripts/snapshot-shelter.mjs [path/to/gallery.json]
// Only `atShelter` cats are kept (never `adopted`), and statuses are dropped: snapshot cats show no status in game.
// Cats with a photo copied into public/pink-paw/ point at that local file so the snapshot also works offline.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { parseGallery, usablePool, foldName } = await import(join(root, 'src/shelter/roster.js'));

const arg = process.argv[2];
const body = arg
  ? JSON.parse(readFileSync(arg, 'utf8'))
  : await (await fetch('https://api.tokentails.com/shelter/rozine-pedute/gallery', { credentials: 'omit' })).json();
const cats = parseGallery(body);
if (!cats || cats.length < 25) throw new Error(`gallery too small (${cats?.length ?? 0} cats)`);

const local = (name, kind) => {
  const f = `pink-paw/${foldName(name).replace(/[^a-z]/g, '')}-${kind}.webp`;
  return existsSync(join(root, 'public', f)) ? f : null;
};
const rows = usablePool(cats).map((c) => ({
  id: c.id, name: c.name,
  photo: local(c.name, 'photo') ?? c.photo ?? null,
  art: local(c.name, 'card') ?? c.art ?? null,
}));

const out = `// src/shelter/snapshot.js  (owner: R): GENERATED by scripts/snapshot-shelter.mjs, do not edit by hand.
// Pink Paw (Rožinė pėdutė) cats at the shelter on ${String(body.generatedAt ?? new Date().toISOString()).slice(0, 10)}. Used off tokentails.com, where the game
// makes no API call. No statuses: the game shows a status only when it is read live.
export const SNAPSHOT = Object.freeze({
  generatedAt: ${JSON.stringify(body.generatedAt ?? null)},
  cats: Object.freeze([
${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}
  ]),
});
`;
writeFileSync(join(root, 'src/shelter/snapshot.js'), out);
console.log(`snapshot: ${rows.length} cats (${rows.filter((r) => !/^https:/.test(r.photo ?? 'https:')).length} with local photos)`);
