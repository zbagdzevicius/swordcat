import * as THREE from 'three';
import * as config from './src/core/config.js';
import { EventBus } from './src/core/EventBus.js';
import { ActorRegistry } from './src/core/ActorRegistry.js';
import { Input } from './src/core/Input.js';
import { GameState } from './src/core/GameState.js';
import { Actor } from './src/core/Actor.js';
import { FollowCamera } from './src/camera/FollowCamera.js';
const ctx = { game: { mode: 'play', loop: { timeScale: 1 }, hitstopT: 0, time: 0, frameCount: 1 }, params: { cam: 'iso' }, bus: new EventBus(), config, scene: new THREE.Scene(), camera: new THREE.PerspectiveCamera(45, 16/9, 0.1, 600), actors: new ActorRegistry(), state: new GameState(), enemies: { list: [], boss: null }, levels: { loading: false }, physics: { heightAt: () => 0, raycast: () => null } };
ctx.renderer = { domElement: { clientWidth: 1280, clientHeight: 720, getBoundingClientRect: () => ({ left: 0, top: 0, width: 1280, height: 720 }) } };
ctx.env = { fogDensity: 0.045, setFocusFog() {} };
ctx.ui = { bar: { insetBottom: 90 }, safeInsets: { top: 0, bottom: 90, left: 0, right: 0, w: 1280, h: 720 } };
ctx.input = new Input(ctx);
const p = new Actor(ctx, { faction: 'player', height: 1 }); p.stateName='move'; p.charge=0; p.onGround=true; ctx.player=p; ctx.actors.register(p,'swordcat');
const comb = process.argv[2] === 'combat';
if (comb) for (let i=0;i<4;i++){ const e=new Actor(ctx,{faction:'enemy',height:1}); e.pos.set(Math.sin(i)*5,0,Math.cos(i)*5); e.object3d.position.copy(e.pos); e.alerted=true; ctx.actors.register(e); }
const cam = new FollowCamera(ctx); ctx.cam = cam; await cam.init();
const mode = process.argv[3] || 'all';
if (mode === 'noocc') cam._isoOcclusion = () => {};
ctx.input.move.y = -1;
const step = (k) => { p.object3d.position.z -= 5.5/60; p.pos.z = p.object3d.position.z; p.vel.set(0,0,-5.5); ctx.game.time += 1/60; cam.update(1/60); cam.render(0,1/60); };
for (let i=0;i<20000;i++) step(i);
let gcs = 0;
globalThis.gc(); const h0 = process.memoryUsage().heapUsed;
for (let i=0;i<2000;i++) step(i);
const h1 = process.memoryUsage().heapUsed;
console.log(process.argv[2]||'explore', mode, 'bytes/frame', ((h1-h0)/2000).toFixed(1));
